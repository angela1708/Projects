// JavaScript Document

// "Data Description" button + text
function toggleTextOne() {
  var text = document.getElementById("appearTextOne");

  if (text.style.display === "none" || text.style.display === "") {
    text.style.display = "block";
  } else {
    text.style.display = "none";
  }
}
document.getElementById("clickedButtonOne").addEventListener("click", toggleTextOne);


